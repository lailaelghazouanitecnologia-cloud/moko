import { CPU6502, Flags } from '../cpu';

export class Palette {
    static readonly SYSTEM_PALETTE: Uint8Array = new Uint8Array([
        0x66, 0x66, 0x66, 0x00, 0x2A, 0x88, 0x14, 0x12, 0xA7, 0x3A, 0x09, 0x87, 0x40, 0x00, 0xA4, 0x00,
        0x51, 0x00, 0x44, 0x00, 0x00, 0x00, 0x00, 0x00, 0x1A, 0x1C, 0x2C, 0x12, 0x53, 0x7E, 0x00, 0x47,
        0x9F, 0x2F, 0x31, 0x2E, 0xB2, 0x00, 0x6A, 0x00, 0x5E, 0x00, 0x50, 0x00, 0x00, 0x00, 0x00, 0x00,
        0xC4, 0xD2, 0x71, 0x5A, 0x9E, 0xFF, 0x4C, 0x73, 0xFF, 0x6D, 0x3E, 0xFF, 0x4F, 0x4F, 0xFF, 0x00,
        0x00, 0x6D, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xFF, 0xFF, 0xFF, 0x4F, 0xC3, 0xFF, 0x68, 0x9E,
        0xFF, 0x83, 0x5A, 0xFF, 0x9C, 0x6B, 0xFF, 0xBF, 0x00, 0xFF, 0xEC, 0x00, 0xAB, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0xFF, 0xFF, 0xFF, 0xA4, 0xFF, 0xFF, 0x9C, 0xD3, 0xFF, 0xBC, 0xD7, 0xFF,
        0xC7, 0xC7, 0xFF, 0xD7, 0xD7, 0xD7, 0xCC, 0xCC, 0xCC, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00
    ]);

    colors: Uint8Array;

    constructor() {
        this.colors = new Uint8Array(32);
    }

    read(address: number): number {
        return this.colors[address & 0x1F];
    }

    write(address: number, value: number): void {
        this.colors[address & 0x1F] = value & 0x3F;
    }

    getColor(index: number): number {
        return this.colors[index & 0x1F];
    }

    getRgb(index: number): [number, number, number] {
        const colorIndex = this.colors[index & 0x1F] & 0x3F;
        const r = Palette.SYSTEM_PALETTE[colorIndex * 3];
        const g = Palette.SYSTEM_PALETTE[colorIndex * 3 + 1];
        const b = Palette.SYSTEM_PALETTE[colorIndex * 3 + 2];
        return [r, g, b];
    }

    getEmphasis(mask: number): [number, number, number] {
        let r = 1.0;
        let g = 1.0;
        let b = 1.0;

        if (mask & 0x20) {
            r *= 0.75;
            g *= 0.75;
        }
        if (mask & 0x40) {
            r *= 0.75;
            b *= 0.75;
        }
        if (mask & 0x80) {
            g *= 0.75;
            b *= 0.75;
        }

        return [r, g, b];
    }

    toRgb(index: number, emphasis: number): [number, number, number] {
        const [r, g, b] = this.getRgb(index);
        const [er, eg, eb] = this.getEmphasis(emphasis);

        return [
            Math.floor(r * er),
            Math.floor(g * eg),
            Math.floor(b * eb)
        ];
    }
}
